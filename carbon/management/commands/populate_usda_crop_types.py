from django.core.management.base import BaseCommand

from carbon.models import CropType, EventTemplate, ProductionTemplate


class Command(BaseCommand):
    help = """
    Unified USDA crop data seeding command for Trazo MVP.

    Seeds 19 crop types with production templates and event templates.
    Safe to run multiple times (idempotent - uses get_or_create).

    Examples:
        python manage.py populate_usda_crop_types           # Full seed
        python manage.py populate_usda_crop_types --crops-only
        python manage.py populate_usda_crop_types --templates-only
    """

    def add_arguments(self, parser):
        parser.add_argument(
            "--crops-only",
            action="store_true",
            help="Only seed CropType records (skip templates)",
        )
        parser.add_argument(
            "--templates-only",
            action="store_true",
            help="Only seed templates for existing crops (skip crop creation)",
        )
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Show what would be created without making changes",
        )

    def handle(self, *args, **options):
        crops_only = options.get("crops_only", False)
        templates_only = options.get("templates_only", False)
        dry_run = options.get("dry_run", False)
        verbosity = options.get("verbosity", 1)

        if dry_run:
            self.stdout.write(self.style.WARNING("DRY RUN MODE - No changes will be made"))

        self.stdout.write(self.style.HTTP_INFO("=" * 60))
        self.stdout.write(self.style.HTTP_INFO("TRAZO MVP - USDA Crop Data Seeding"))
        self.stdout.write(self.style.HTTP_INFO("=" * 60))

        stats = {
            "crops_created": 0,
            "crops_updated": 0,
            "templates_created": 0,
            "templates_skipped": 0,
            "events_created": 0,
        }

        # Step 1: Seed crop types (unless templates-only)
        if not templates_only:
            self.stdout.write("\n📦 Step 1: Seeding USDA Crop Types...")
            stats = self._seed_crop_types(stats, dry_run, verbosity)
        else:
            self.stdout.write("\n⏭️  Skipping crop types (--templates-only)")

        # Step 2: Seed production templates (unless crops-only)
        if not crops_only:
            self.stdout.write("\n📋 Step 2: Seeding Production Templates...")
            stats = self._seed_production_templates(stats, dry_run, verbosity)
        else:
            self.stdout.write("\n⏭️  Skipping templates (--crops-only)")

        # Final summary
        self._print_summary(stats, dry_run)

    # Fields in seed data that don't exist on the CropType model
    IGNORED_FIELDS = {"benchmark_verified", "emissions_calculation_method", "usda_benchmark_source"}

    def _seed_crop_types(self, stats, dry_run, verbosity):
        """Seed all 19 USDA-verified crop types."""
        crop_data = self._get_crop_type_data()

        for data in crop_data:
            if dry_run:
                self.stdout.write(f"  Would create/update: {data['name']}")
                continue

            # Strip fields that don't exist on the CropType model
            clean_data = {k: v for k, v in data.items() if k not in self.IGNORED_FIELDS}

            crop_type, created = CropType.objects.get_or_create(slug=clean_data["slug"], defaults=clean_data)

            if created:
                stats["crops_created"] += 1
                if verbosity >= 2:
                    self.stdout.write(self.style.SUCCESS(f"  ✅ Created: {crop_type.name}"))
            else:
                # Update existing with new data
                for key, value in clean_data.items():
                    setattr(crop_type, key, value)
                crop_type.save()
                stats["crops_updated"] += 1
                if verbosity >= 2:
                    self.stdout.write(self.style.WARNING(f"  🔄 Updated: {crop_type.name}"))

        return stats

    def _seed_production_templates(self, stats, dry_run, verbosity):
        """Seed production templates and their events for all crops."""
        template_data = self._get_template_data()

        # Build lookup dict for dry-run mode
        crop_name_lookup = {crop["slug"]: crop["name"] for crop in self._get_crop_type_data()}

        for crop_slug, tpl_data in template_data.items():
            # In dry-run mode, skip database queries
            if dry_run:
                crop_name = crop_name_lookup.get(crop_slug, crop_slug)
                self.stdout.write(f"  Would create template: {crop_name}")
                continue

            try:
                crop_type = CropType.objects.get(slug=crop_slug)
            except CropType.DoesNotExist:
                self.stdout.write(
                    self.style.ERROR(f"  ❌ Crop '{crop_slug}' not found - run without --templates-only first")
                )
                continue

            template_slug = f"{crop_slug}_conventional"

            # Check if template exists
            existing = ProductionTemplate.objects.filter(crop_type=crop_type, slug=template_slug).first()

            if existing:
                stats["templates_skipped"] += 1
                if verbosity >= 2:
                    self.stdout.write(f"  ⏭️  Template exists: {crop_type.name}")
                continue

            # Create production template
            template = ProductionTemplate.objects.create(
                crop_type=crop_type,
                name=f"{crop_type.name} - Conventional Production",
                slug=template_slug,
                farming_approach="conventional",
                description=tpl_data["description"],
                complexity_level=tpl_data.get("complexity", "intermediate"),
                estimated_setup_time=tpl_data.get("setup_time", 8),
                projected_emissions_reduction=0.0,
                projected_cost_change=0.0,
                projected_yield_impact=0.0,
                premium_pricing_potential=tpl_data.get("premium", "10-20%"),
                market_demand=tpl_data.get("market_demand", "high"),
                certification_requirements=[],
                compliance_notes=tpl_data.get("compliance_notes", ""),
                is_active=True,
                is_recommended=tpl_data.get("is_recommended", False),
                usda_reviewed=True,
                usda_compliant=True,
            )
            stats["templates_created"] += 1

            if verbosity >= 2:
                self.stdout.write(self.style.SUCCESS(f"  ✅ Created template: {crop_type.name}"))

            # Create event templates
            for event_data in tpl_data.get("events", []):
                EventTemplate.objects.create(
                    production_template=template,
                    name=event_data["name"],
                    event_type=event_data["event_type"],
                    description=event_data["description"],
                    timing=event_data["timing"],
                    frequency=event_data.get("frequency", "seasonal"),
                    typical_duration=event_data.get("duration", "2-4 hours"),
                    order_sequence=event_data.get("order", 0),
                    carbon_impact=event_data.get("carbon_impact", 25.0),
                    carbon_category=event_data.get("carbon_category", "medium"),
                    carbon_sources=event_data.get("carbon_sources", []),
                    typical_amounts=event_data.get("typical_amounts", {}),
                    cost_estimate=event_data.get("cost_estimate", 100.0),
                    labor_hours=event_data.get("labor_hours", 4.0),
                    efficiency_tips=event_data.get("efficiency_tips", ""),
                    sustainability_score=event_data.get("sustainability_score", 5),
                    alternative_methods=event_data.get("alternative_methods", []),
                    qr_visibility=event_data.get("qr_visibility", "medium"),
                    consumer_message=event_data.get("consumer_message", ""),
                    backend_event_type=event_data.get("backend_event_type", 2),
                    backend_event_fields=event_data.get("backend_event_fields", {}),
                    usda_practice_code=event_data.get("usda_practice_code", ""),
                    usda_compliant=True,
                    emission_factor_source="USDA Agricultural Research Service",
                    display_priority=event_data.get("display_priority", 3),
                    template_category=event_data.get("template_category", "core"),
                    is_active=True,
                    is_default_enabled=event_data.get("is_default_enabled", True),
                    is_required=event_data.get("is_required", False),
                )
                stats["events_created"] += 1

        return stats

    def _print_summary(self, stats, dry_run):
        """Print final summary."""
        self.stdout.write("\n" + "=" * 60)
        if dry_run:
            self.stdout.write(self.style.WARNING("DRY RUN COMPLETE - No changes made"))
        else:
            self.stdout.write(self.style.SUCCESS("SEEDING COMPLETE"))

        self.stdout.write("=" * 60)
        self.stdout.write(f"\n📊 SUMMARY:")
        self.stdout.write(f"   Crop Types Created:    {stats['crops_created']}")
        self.stdout.write(f"   Crop Types Updated:    {stats['crops_updated']}")
        self.stdout.write(f"   Templates Created:     {stats['templates_created']}")
        self.stdout.write(f"   Templates Skipped:     {stats['templates_skipped']}")
        self.stdout.write(f"   Events Created:        {stats['events_created']}")

        # Skip database verification in dry-run mode
        if dry_run:
            total_crops = len(self._get_crop_type_data())
            total_templates = len(self._get_template_data())
            self.stdout.write(f"\n📈 EXPECTED TOTALS (dry-run):")
            self.stdout.write(f"   Crop Types:            {total_crops}")
            self.stdout.write(f"   Templates:             {total_templates}")
            self.stdout.write(
                self.style.SUCCESS(
                    f"\n✅ After running, production dropdown will show {total_crops} USDA-verified crop types!"
                )
            )
            return

        # Verify totals from database
        total_crops = CropType.objects.filter(is_active=True).count()
        total_templates = ProductionTemplate.objects.filter(is_active=True).count()
        total_events = EventTemplate.objects.filter(is_active=True).count()

        self.stdout.write(f"\n📈 DATABASE TOTALS:")
        self.stdout.write(f"   Active Crop Types:     {total_crops}")
        self.stdout.write(f"   Active Templates:      {total_templates}")
        self.stdout.write(f"   Active Events:         {total_events}")

        self.stdout.write(
            self.style.SUCCESS(f"\n✅ Production dropdown will show {total_crops} USDA-verified crop types!")
        )

