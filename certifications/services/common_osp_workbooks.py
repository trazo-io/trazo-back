def build_workbook(establishment, key: str, generated_on=None, osp=None) -> io.BytesIO:
    """Render one attachment as .xlsx.

    xlsx, not PDF or CSV: the USDA publishes these as Excel workbooks and certifiers expect a
    file they can edit — the operator still has to complete the cells Trazo left blank.

    🔴 `osp` names WHICH plan's declared materials the Materials List states. It used to be
    unaskable: the sheet resolved the plan itself, active-first, so a packet generated for a
    DRAFT under revision shipped module PDFs describing that draft beside a Materials List
    describing the plan it replaces. One packet, two plans — the failure this whole module was
    written to end. Both callers that HAVE a plan now name it (the packet and the panel's
    download); omitting it falls back to active-first, which is what it always did.
    """
    from openpyxl import Workbook as XLWorkbook
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    spec = WORKBOOKS_BY_KEY.get(key)
    if spec is None:
        raise ValueError(f"Unknown Common OSP workbook: {key!r}")

    if generated_on is None:
        from django.utils import timezone

        generated_on = timezone.now().date()

    wb = XLWorkbook()
    ws = wb.active
    # Excel sheet TAB names are capped at 31 chars and reject \ / ? * [ ] : outright — openpyxl
    # raises on them. "Crop/Livestock Product List" hits this. Only the tab is sanitized; cell A1
    # below keeps the USDA title verbatim, which is the copy that matters to a certifier.
    ws.title = _sheet_tab_name(spec.title)

    bold = Font(bold=True)
    header_fill = PatternFill("solid", fgColor="E2EFDA")
    wrap = Alignment(wrap_text=True, vertical="top")

    ws.append([spec.title])
    ws["A1"].font = Font(bold=True, size=14)

    # The Common OSP attachments ship INSIDE the renewal packet ZIP alongside the module
    # PDFs, so a packet whose PDFs are watermarked and whose workbooks are not is exactly
    # the sibling-surface split this marking exists to prevent — and the workbook is the
    # file a certifier is most likely to open, edit and keep, because it is the one they
    # are meant to complete. Row 2, above the instructions, in the same red as the PDF wash.
    if is_specimen(establishment):
        ws.append([SPECIMEN_LINE])
        ws.cell(row=ws.max_row, column=1).font = Font(bold=True, color="C62828")
    ws.append([spec.instructions])
    ws.append([PROVENANCE.format(date=generated_on.isoformat())])
    ws.append([])

    for declaration in spec.declarations:
        ws.append([f"☐  {declaration}"])
    if spec.declarations:
        ws.append([])

    header_row = ws.max_row + 1
    ws.append([c.header for c in spec.columns])
    for idx, column in enumerate(spec.columns, start=1):
        cell = ws.cell(row=header_row, column=idx)
        cell.font = bold
        cell.fill = header_fill
        cell.alignment = wrap
        ws.column_dimensions[get_column_letter(idx)].width = column.width

    sources = list(spec.rows(establishment, osp))
    for source in sources:
        values = []
        for column in spec.columns:
            try:
                value = column.value(source, establishment)
            except Exception:  # noqa: BLE001 — one bad cell must not lose the whole attachment
                logger.exception("Common OSP workbook %r: column %r failed", key, column.header)
                value = None
            values.append(_defuse_formula(value))
        ws.append(values)

    for row in ws.iter_rows(min_row=header_row + 1):
        for cell in row:
            cell.alignment = wrap

    if spec.footer is not None:
        ws.append([])
        try:
            footer_rows = list(spec.footer(establishment, osp, sources))
        except Exception:  # noqa: BLE001 — a failed total is a missing total, not a lost sheet
            logger.exception("Common OSP workbook %r: footer failed", key)
            footer_rows = []
        for label, value in footer_rows:
            ws.append([label, _defuse_formula(value)])
            ws.cell(row=ws.max_row, column=1).font = bold

    # Wrap the long instruction/provenance lines rather than letting them run off the sheet.
    for row_idx in (2, 3):
        ws.cell(row=row_idx, column=1).alignment = Alignment(wrap_text=True, vertical="top")

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer


def workbook_summary(establishment, osp=None) -> list[dict]:
    """Per-workbook row and blank-cell counts, for a UI that tells the operator what is left.

    🔴 2026-09-07 — `blank_cells` counted EVERY empty cell, including columns that are blank by
    construction: Comments, the six export-equivalency countries a domestic grower opts out of on
    the sheet's own printed declaration, "Imports" under "I do not import". A four-product
    operation was told its Crop/Livestock Product List had "36 cells for you to fill" when the
    truthful number was zero, and a panel that overstates work by an order of magnitude gets
    read as noise — which is the opposite of what these counts are for.

    Three numbers now, because they are three different asks:

      `missing_from_records` — Trazo fills this column from a record and the record is empty.
                               Fixable IN Trazo, which makes it the only one worth nagging about.
      `needs_your_answer`    — only the operator can supply it (a supplier's own certifier).
                               Real work; nothing Trazo could do about it.
      `optional_blanks`      — the form permits it. Reported so the total still reconciles
                               against the sheet, never presented as work.

    `blank_cells` is kept as the sum of the first two — a count of work remaining, never a
    completeness score.
    """
    summary = []
    for spec in workbooks_for(_packet_agent(establishment, osp)):
        try:
            rows = list(spec.rows(establishment, osp))
        except Exception:  # noqa: BLE001
            logger.exception("Common OSP workbook %r: row source failed", spec.key)
            summary.append(
                {
                    "key": spec.key,
                    "title": spec.title,
                    "rows": 0,
                    "blank_cells": 0,
                    "missing_from_records": 0,
                    "needs_your_answer": 0,
                    "optional_blanks": 0,
                    "blanks": [],
                    "error": True,
                }
            )
            continue

        counts = {"record": 0, "operator": 0, "optional": 0}
        # Keyed by POSITION, not by header. Two columns of one USDA form may legitimately carry
        # the same header ("Comments", "Date"), and keying on the text would merge their counts
        # and then emit the merged number once per column — one blank reported twice.
        per_column: dict = {}
        for source in rows:
            for index, column in enumerate(spec.columns):
                try:
                    empty = column.value(source, establishment) is None
                except Exception:  # noqa: BLE001 — a column that raises is a cell nobody filled
                    empty = True
                if empty:
                    counts[column.blank_kind] += 1
                    per_column[index] = per_column.get(index, 0) + 1
        summary.append(
            {
                "key": spec.key,
                "title": spec.title,
                "rows": len(rows),
                "blank_cells": counts["record"] + counts["operator"],
                "missing_from_records": counts["record"],
                "needs_your_answer": counts["operator"],
                "optional_blanks": counts["optional"],
                # WHICH columns are blank, and where each is answered. A total on its own sends
                # the operator looking; "Last prohibited input — 6, in the parcel's field
                # history" is the same number with somewhere to go. Optional blanks are left
                # out: the form permits them, so listing them would reintroduce as a to-do list
                # exactly what the three counts stopped presenting as work.
                "blanks": [
                    {
                        "header": column.header,
                        "count": per_column[index],
                        "kind": column.blank_kind,
                        "fix": column.fix_hint,
                    }
                    for index, column in enumerate(spec.columns)
                    if per_column.get(index) and column.blank_kind != "optional"
                ],
                "error": False,
            }
        )
    return summary
