def _field_rows(establishment):
    """One row per parcel per certification year, newest crop-history entry first.

    A parcel with no crop history still gets a row — the field exists and must appear on the
    form; its crop and prohibited-input cells are simply blank for the operator to fill.
    """
    from product.models import Parcel

    parcels = Parcel.objects.filter(establishment=establishment).prefetch_related("crop_history").order_by("name")
    rows = []
    for parcel in parcels:
        history = sorted(parcel.crop_history.all(), key=lambda h: h.year, reverse=True)
        rows.append((parcel, history[0] if history else None, _current_season_crop(parcel, history)))
    return rows


def _current_season_crop(parcel, crop_history) -> Optional[str]:
    """The crop this parcel is actually carrying, when that is newer than its crop history.

    🔴 2026-08-21 — this form printed the newest `ParcelCropHistory` row and nothing else. A
    farm whose field history was filled through 2025 but which had 2026 seasons running in
    Trazo therefore filed a Field and Crop Information Form saying Upper Terrace grows a
    "Full-season cover crop" while the SAME packet's contents page listed "Upper Terrace —
    Onions — 2026-04-01", and Bottom Ground B was filed as onions in a year it grew carrots.
    The field list is the first page an inspector reads, so a packet that contradicts itself
    there costs the operation its credibility before anyone reaches the records.

    `ParcelCropHistory` is the § 205.202(b) 36-month history and stays the source for prior
    years. But Trazo already knows what is in the ground now — it is the production the
    operator opened — so when the newest season is more recent than the newest history row,
    the current crop is named from that season. Nothing is invented: both sides are the
    operation's own records, and the prior-year history is untouched.
    """
    from history.models import History

    newest_history_year = max((h.year for h in crop_history), default=None)
    season = (
        # `start_date__isnull=False` in the FILTER, not a check on the winner: ordering by
        # "-start_date" can put a null-dated season first, and bailing on it would hide a
        # real dated season sitting behind it.
        History.objects.filter(parcel=parcel, start_date__isnull=False)
        .select_related("product", "crop_type")
        .order_by("-start_date")
        .first()
    )
    if season is None:
        return None
    season_year = season.start_date.year
    if newest_history_year is not None and newest_history_year >= season_year:
        return None
    crop = getattr(season.product, "name", None) or getattr(season.crop_type, "name", None)
    if not crop:
        return None
    # A season that opens in one year and closes in the next is "2026–27", not "2026": an
    # overwintered spinach drilled in October and cut in April was filed as "Spinach (2026
    # season)" on a form for the year it was actually harvested, and read as stale.
    end = season.finish_date or season.expected_harvest
    if end is not None and end.year > season_year:
        return f"{crop} ({season_year}\u2013{str(end.year)[-2:]} season)"
    return f"{crop} ({season_year} season)"


def _product_rows(establishment):
    from history.models import History

    seen = {}
    for h in (
        History.objects.filter(parcel__establishment=establishment)
        .select_related("product", "crop_type")
        .order_by("product__name")
    ):
        name = getattr(h.product, "name", None) or getattr(h.crop_type, "name", None)
        if name and name not in seen:
            seen[name] = h
    return list(seen.values())


def _material_rows(establishment):
    """Distinct inputs applied on this operation — chemical products and soil amendments.

    Deduplicated by product name because the Materials List is a list of PRODUCTS, not of
    applications: an input sprayed twelve times is one row.
    """
    from history.models import ChemicalEvent, SoilManagementEvent

    seen = {}
    for e in ChemicalEvent.objects.filter(history__parcel__establishment=establishment):
        name = _blank(e.commercial_name)
        if name and name.lower() not in seen:
            seen[name.lower()] = ("chemical", e)
    for e in SoilManagementEvent.objects.filter(history__parcel__establishment=establishment):
        name = _blank(e.amendment_product_name)
        if name and name.lower() not in seen:
            seen[name.lower()] = ("amendment", e)
    return list(seen.values())


def _supplier_rows(establishment):
    """Distinct suppliers of purchased products — inputs, amendments and seed.

    Keyed on (product, supplier) because the USDA form wants one row per product per supplier,
    not one row per supplier.

    🔴 2026-08-16: soil amendments were absent entirely, because `SoilManagementEvent` had no
    supplier column. On an organic orchard the compost supplier is usually the largest single
    line on this form, and the generated workbook simply did not have it.

    🔴 2026-08-17, the SECOND instance of that same defect: beneficial-organism suppliers were
    absent. The workbook's own USDA instruction line opens with "live animals", and a
    Trichogramma or lacewing release is bought from a named supplier exactly like a fertiliser
    is — `PestManagementEvent.beneficial_supplier` has held it since the BR subtype shipped and
    no row was ever emitted. Every event model that carries a supplier string belongs here; the
    lesson from two rounds is to enumerate the MODELS, not to remember the ones that came up.
    """
    from history.models import ChemicalEvent, PestManagementEvent, ProductionEvent, SoilManagementEvent

    seen = {}
    for e in ChemicalEvent.objects.filter(history__parcel__establishment=establishment):
        product, supplier = _blank(e.commercial_name), _blank(e.supplier_name)
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    for e in SoilManagementEvent.objects.filter(history__parcel__establishment=establishment):
        # Off-farm MANURE puts its supplier in `amendment_manufacturer`, by the convention
        # stated in SoilManagementEvent.manure_origin's own help_text ("a second supplier
        # field would be a second writer of one fact"). Reading only amendment_supplier_name
        # emitted zero Supplier List rows for exactly the operators who followed the model —
        # the third instance of this omission, after soil amendments (08-16) and beneficial
        # organisms (08-17). Those two enumerated the MODELS; this one is the FIELDS on a
        # model that can hold a supplier.
        supplier = _blank(e.amendment_supplier_name) or (
            _blank(e.amendment_manufacturer) if e.manure_origin == "off_farm" else None
        )
        # The product name, falling back to the generic category — a Supplier List row reading
        # "— / Bu's Compost Co." tells a certifier nothing about what was bought.
        product = _blank(e.amendment_product_name) or _blank(e.amendment_type)
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    seed_events = ProductionEvent.objects.filter(
        history__parcel__establishment=establishment, type__in=("PL", "TR")
    ).select_related("history__product", "history__crop_type")
    for e in seed_events:
        supplier = _blank(e.seed_supplier_name)
        # The CROP, not the production. `history.name` is a season label like
        # "Hass Avocado Hillside Grove A 2026"; writing that into the USDA "Product Name" column
        # describes a season to a certifier who expects the product the supplier provided.
        product = _blank(getattr(e.history.product, "name", None) or getattr(e.history.crop_type, "name", None))
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("seed", product, supplier)
    for e in PestManagementEvent.objects.filter(history__parcel__establishment=establishment):
        supplier = _blank(e.beneficial_supplier)
        # The organism, falling back to the generic category. A row reading "— / Rincon-Vitova"
        # tells a certifier nothing about what was released.
        product = _blank(e.beneficial_species) or "Beneficial organisms"
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    return list(seen.values())


