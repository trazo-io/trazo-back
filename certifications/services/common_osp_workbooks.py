def _field_status(row):
    """USDA 'Status' column: exactly one of Organic or Transitional."""
    history = row[1]
    method = (getattr(history, "production_method", None) or "").lower() if history else ""
    if method == "organic":
        return "Organic"
    if method == "transitional":
        return "Transitional"
    return None


def _last_prohibited(row):
    """USDA: 'Name and Application Date of Last Prohibited Input'.

    Required for EVERY field, including organic ones. Emits only what is recorded — name, date,
    or "name, date" — and blank when neither is. Never derived from `substances_applied`: that
    column lists everything applied in a year and cannot identify which was the last prohibited
    input without guessing, and a guess here is a false statement about land history.

    🔴 2026-08-23 — this read `row[1]`, the NEWEST crop-history year, and nothing else. The
    "last prohibited input" is the most recent one EVER recorded on the field, which on any
    ground that has since had a clean year sits in an OLDER row. So the cell was blank on
    exactly the parcels where it matters most: a 9.8-acre lease with glyphosate on 10 Jun 2023
    in its 2023 row and three clean years after it filed a Field and Crop Information Form with
    this column empty — while the Parcel Application in the same packet printed the date.
    Scans every year; the latest dated entry wins.
    """
    parcel = row[0]
    rows = [h for h in parcel.crop_history.all() if getattr(h, "date_last_prohibited", None)]
    if not rows:
        # No dated entry anywhere — fall back to a name-only entry on the newest row, which is
        # all the previous code could ever have shown.
        history = row[1]
        return _blank(getattr(history, "last_prohibited_substance", None)) if history else None
    latest = max(rows, key=lambda h: h.date_last_prohibited)
    name = _blank(getattr(latest, "last_prohibited_substance", None))
    date_text = latest.date_last_prohibited.strftime("%-m/%-d/%Y")
    return f"{name}, {date_text}" if name else date_text


def _fact_location(row, establishment):
    """OTCO FACT-04 column 1 — the parcel's name and where it is.

    The example on the form is "City Ranch, 260 SW Madison, Corvallis, OR 97333": one cell, name
    then address. `Parcel.address` is the operator's own entry and prints as written; a parcel with
    no address prints its name alone rather than borrowing the establishment's address, which may
    be a different town.
    """
    parcel = row[0]
    address = _blank(getattr(parcel, "address", None))
    return f"{parcel.name}, {address}" if address else _blank(parcel.name)


def _fact_status(row):
    """OTCO FACT-04 'Status' — never blank.

    The USDA form's status cell (`_field_status`) is blank unless the newest history row says
    Organic or Transitional, because that form lists only land requested for certification. FACT-04
    is completed by a certified operation about parcels already on its certificate, and a blank
    there reads as an unanswered question rather than a scope decision. So this prints what the
    record says, in the operator's own vocabulary: "Organic" / "Transitional" when recorded, the
    recorded method otherwise (a conventional block on a split operation is a fact, not an
    omission), and "No status recorded" when the parcel has no field history at all — a statement
    the operator can act on in the parcel's field history, never a guess.
    """
    known = _field_status(row)
    if known:
        return known
    history = row[1]
    method = _blank(getattr(history, "production_method", None)) if history else None
    if method:
        return method.replace("_", " ").capitalize()
    return "No status recorded"


def _fact_crops(row, establishment):
    """OTCO FACT-04 'Crop(s) and Acreage' — "Alfalfa (20 acres), Oats (20 acres)".

    Trazo records no per-crop acreage inside a parcel, so the only acreage that can be stated
    truthfully is the whole parcel's — against one crop, or against each crop of a double crop,
    where every crop occupies the whole parcel in turn ("Spinach (18.6 acres), then Carrots
    (18.6 acres)"). Crops whose seasons overlap, or whose end is unknown, may share the parcel;
    that case names the crops and says the per-crop acreage is not recorded, rather than dividing
    the parcel evenly — an invented figure on a form the certifier reconciles against the
    certificate.
    """
    current = row[2]
    acres = _acres(row[0].area)
    if current is not None:
        if acres is None:
            joiner = ", then " if current.sequential else ", "
            return f"{joiner.join(current.crops)} \u2014 {current.season} season"
        if len(current.crops) == 1 or current.sequential:
            listed = ", then ".join(f"{crop} ({acres:g} acres)" for crop in current.crops)
            return f"{listed} \u2014 {current.season} season"
        return f"{', '.join(current.crops)} \u2014 {current.season} season; acreage per crop not recorded"
    crop = _blank(getattr(row[1], "crop_grown", None) if row[1] else None)
    if not crop:
        return None
    return f"{crop} ({acres:g} acres)" if acres is not None else crop


def _fact_totals(establishment, osp, rows):
    """OTCO FACT-04 footer — the two acreage totals, summed from the sheet's own rows.

    Only rows whose status is Organic or Transitional contribute; a conventional block or a parcel
    with no recorded status is listed above but is not "requested for certification" and would
    inflate a total the reviewer reconciles against the certificate. Parcels with no recorded area
    are skipped, and the footer says how many, so a low total is a stated gap rather than a
    quiet one.
    """
    organic = transitional = 0.0
    unsized = 0
    for row in rows:
        acres = _acres(row[0].area)
        status = _field_status(row)
        if status is None:
            continue
        if acres is None:
            unsized += 1
            continue
        if status == "Organic":
            organic += acres
        elif status == "Transitional":
            transitional += acres
    out = [
        ("Total Transitional Acres Requested For Certification", round(transitional, 2)),
        ("Total Organic Acres Requested For Certification", round(organic, 2)),
    ]
    if unsized:
        out.append((f"Parcels without a recorded area, not included in the totals above: {unsized}", None))
    return out


def workbooks_for(agent: Optional[str]) -> list:
    """The sheets a packet numbered to `agent` carries: every agent-neutral sheet, plus that agent's own."""
    return [spec for spec in WORKBOOKS if not spec.agents or (agent and agent in spec.agents)]


def _packet_agent(establishment, osp=None) -> Optional[str]:
    """The slug of the agent that reviews this plan, or None when unresolved.

    Resolved the way the packet resolves it (`packet_coverage.packet_agent`: the plan's own answer,
    then the certificate of record, then other records), so the attachments panel and the ZIP list
    the same sheets. A known agent with no register (OCI) yields a slug no sheet claims, so it gets
    the agent-neutral sheets only, as the ZIP does.
    """
    try:
        from certifications.services.packet_coverage import resolve_certifier

        if osp is not None:
            return resolve_certifier(osp)
        plan = _current_osp(establishment)
        return resolve_certifier(plan) if plan is not None else None
    except Exception:  # noqa: BLE001 — an unresolved agent means the neutral sheets only
        logger.exception(
            "Could not resolve the certifying agent for establishment %s", getattr(establishment, "pk", None)
        )
        return None


