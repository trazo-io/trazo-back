def _field_rows(establishment, osp=None):
    """One row per parcel per certification year, newest crop-history entry first.

    A parcel with no crop history still gets a row — the field exists and must appear on the
    form; its crop and prohibited-input cells are simply blank for the operator to fill.
    """
    from product.models import Parcel

    parcels = Parcel.objects.filter(establishment=establishment).prefetch_related("crop_history").order_by("name")
    rows = []
    for parcel in parcels:
        history = sorted(parcel.crop_history.all(), key=lambda h: h.year, reverse=True)
        rows.append((parcel, history[0] if history else None, _current_season_crops(parcel, history)))
    return rows


def _day(value):
    """A date, whether the column holds a date or a datetime — so two seasons always compare."""
    return value.date() if hasattr(value, "date") and callable(value.date) else value


@dataclass(frozen=True)
class SeasonCrops:
    """Every crop a parcel carries in its newest season year, in planting order.

    🔴 2026-09-10 (OTCO desk read) — this was ONE season, the newest by start date. Bottom Ground A
    grew spring spinach and then a second carrot crop in 2026; FACT-04 and the Field and Crop form
    both filed carrots alone, while the same packet's harvest and sales records traced a spinach lot
    off that parcel. A reviewer reconciling the table against the audit trail finds a crop the table
    omits, and asks for a corrected form.
    """

    crops: tuple
    season: str  # "2026", or "2026–27" when a season runs into the next year
    #: Each season ends before the next begins — a double crop. Only then does every crop occupy the
    #: whole parcel in turn, so only then may FACT-04 state the parcel's acreage against each crop.
    sequential: bool

    def label(self) -> str:
        return f"{(', then ' if self.sequential else ', ').join(self.crops)} ({self.season} season)"


def _current_season_crops(parcel, crop_history) -> Optional[SeasonCrops]:
    """The crops this parcel is actually carrying, when that is newer than its crop history.

    🔴 2026-08-21 — this form printed the newest `ParcelCropHistory` row and nothing else. A
    farm whose field history was filled through 2025 but which had 2026 seasons running in
    Trazo therefore filed a Field and Crop Information Form saying Upper Terrace grows a
    "Full-season cover crop" while the SAME packet's contents page listed "Upper Terrace —
    Onions — 2026-04-01", and Bottom Ground B was filed as onions in a year it grew carrots.
    The field list is the first page an inspector reads, so a packet that contradicts itself
    there costs the operation its credibility before anyone reaches the records.

    `ParcelCropHistory` is the § 205.202(b) 36-month history and stays the source for prior
    years. But Trazo already knows what is in the ground now — it is the production the
    operator opened — so when the newest season is more recent than the newest history row,
    the current crop is named from that season. Nothing is invented: both sides are the
    operation's own records, and the prior-year history is untouched.
    """
    from history.models import History

    newest_history_year = max((h.year for h in crop_history), default=None)
    seasons = list(
        # `start_date__isnull=False` in the FILTER: a null-dated season has no year to belong to,
        # and letting one sort into the list would hide the dated seasons around it.
        History.objects.filter(parcel=parcel, start_date__isnull=False)
        .select_related("product", "crop_type")
        .order_by("start_date", "pk")
    )
    if not seasons:
        return None
    season_year = seasons[-1].start_date.year
    if newest_history_year is not None and newest_history_year >= season_year:
        return None
    current = [season for season in seasons if season.start_date.year == season_year]
    crops: list = []
    for season in current:
        crop = getattr(season.product, "name", None) or getattr(season.crop_type, "name", None)
        if crop and crop not in crops:
            crops.append(crop)
    if not crops:
        return None
    ends = [season.finish_date or season.expected_harvest for season in current]
    # Unknown end = not provably sequential. Stating the whole parcel against each of two crops
    # that may share it would be an invented acreage, so the benefit of the doubt goes to "no number".
    sequential = all(
        end is not None and _day(end) <= _day(following.start_date) for end, following in zip(ends, current[1:])
    )
    # A season that opens in one year and closes in the next is "2026–27", not "2026": an
    # overwintered spinach drilled in October and cut in April was filed as "Spinach (2026
    # season)" on a form for the year it was actually harvested, and read as stale.
    last_end = max((_day(end) for end in ends if end is not None), default=None)
    if last_end is not None and last_end.year > season_year:
        label = f"{season_year}\u2013{str(last_end.year)[-2:]}"
    else:
        label = str(season_year)
    return SeasonCrops(crops=tuple(crops), season=label, sequential=sequential)


def _product_rows(establishment, osp=None):
    from history.models import History

    seen = {}
    for h in (
        History.objects.filter(parcel__establishment=establishment)
        .select_related("product", "crop_type")
        .order_by("product__name")
    ):
        name = getattr(h.product, "name", None) or getattr(h.crop_type, "name", None)
        if name and name not in seen:
            seen[name] = h
    return list(seen.values())


@dataclass(frozen=True)
class MaterialRow:
    """One product on the Materials List, from the record layer and/or the plan.

    Two sources, joined by product name, because the USDA instruction is "List ALL inputs and
    materials used OR INTENDED FOR USE" and neither source alone answers it:

      * logged applications say what was actually used, and nothing about intent;
      * the plan's own materials list says what the operator has declared — including a material
        bought for next season that no event mentions yet.

    Reading only the events made the attachment under-report exactly the materials the form asks
    about most directly, and left "In use / Intended for use" blank on every row while the answer
    sat on the plan in `PlanMaterialEntry.status`.
    """

    name: str
    kind: str  # "chemical" | "amendment" | "plan"
    event: object = None
    plan: object = None  # PlanMaterial, when this product is on the plan


def _current_osp(establishment):
    """The plan these attachments describe — active if there is one, else the newest.

    Same rule the audit export uses (`audit_export_service`), deliberately: an attachment and the
    dossier that ships beside it must not describe two different plans.
    """
    from certifications.models import OrganicSystemPlan

    return (
        OrganicSystemPlan.objects.filter(establishment=establishment, status="active")
        .order_by("-version_number")
        .first()
        or OrganicSystemPlan.objects.filter(establishment=establishment).order_by("-version_number").first()
    )


def _norm_name(value) -> str:
    """Match key for a product name — same rule `plan_materials._norm` uses.

    Whitespace-collapsing matters: `.lower()` alone left "Champ  WG" (a double space, which is
    what a paste from a label produces) unmatched against "Champ WG", so the same product
    appeared as two rows — one from the log with no use status, one from the plan with no
    manufacturer.
    """
    return " ".join(str(value or "").split()).strip().lower()


def _richer_plan(current, candidate):
    """Of two plan rows for the same product, the one that actually says something.

    🔴 A product can sit on more than one of the four sources — the codebase notes that a
    product like Neptune's Harvest is on both OMRI and the WSDA list, and CCOF treats them as
    co-equal. `plan_materials()` returns them in source order (National List, OMRI,
    operator-entered, WSDA), so a plain last-wins merge let the WSDA row overwrite the
    operator-entered one — and the operator-entered row is the ONLY source that carries
    `reason` and `status`, which is the whole reason this join exists. It would have failed
    silently: the columns would simply be blank again.
    """
    if current is None:
        return candidate
    current_says = bool(getattr(current, "reason", "") or getattr(current, "status", ""))
    candidate_says = bool(getattr(candidate, "reason", "") or getattr(candidate, "status", ""))
    if candidate_says and not current_says:
        return candidate
    if current_says and not candidate_says:
        return current
    # Neither (or both) carry the operator's answers — prefer whichever names a manufacturer.
    if not _blank(getattr(current, "manufacturer", None)) and _blank(getattr(candidate, "manufacturer", None)):
        return candidate
    return current


def _material_rows(establishment, osp=None):
    """Distinct inputs on this operation — applied, declared on the plan, or both.

    `osp` names WHICH plan's declared materials to union in. Every caller that has a plan
    passes it — the editor, the panel's download, the packet — because a draft under revision is
    not necessarily the active one, and a sheet that resolved the plan for itself is how one
    packet came to carry module PDFs for a draft beside a Materials List for the plan it
    replaces. `None` falls back to `_current_osp` for a caller with no plan in hand.

    Deduplicated by product name because the Materials List is a list of PRODUCTS, not of
    applications: an input sprayed twelve times is one row.

    Plan materials are read through `plan_materials()` — the ONE reading of the plan's list.
    Querying the registries here instead is precisely the defect that produced four disagreeing
    materials lists in a single packet.
    """
    from history.models import ChemicalEvent, ProductionEvent, SoilManagementEvent

    rows: dict = {}
    for e in ChemicalEvent.objects.filter(history__parcel__establishment=establishment):
        name = _blank(e.commercial_name)
        if name and _norm_name(name) not in rows:
            rows[_norm_name(name)] = MaterialRow(name=name, kind="chemical", event=e)
    for e in SoilManagementEvent.objects.filter(history__parcel__establishment=establishment):
        name = _blank(e.amendment_product_name)
        if name and _norm_name(name) not in rows:
            rows[_norm_name(name)] = MaterialRow(name=name, kind="amendment", event=e)
    # Post-harvest sanitizers (2026-09-12). A wash-water sanitizer is a material the form asks
    # for — CCOF Materials Application §D, WSDA AGR 2196 "sanitizer" purpose, OTCO C11 — and
    # its record is a post-harvest processing event naming `sanitizer_name`, which this list
    # never read. So the pilot's flume sanitizer was on the plan under one name, in the log
    # under another, and absent from the one attachment whose job is to reconcile the two.
    for e in ProductionEvent.objects.filter(history__parcel__establishment=establishment, type="PH").exclude(
        sanitizer_name__isnull=True
    ):
        name = _blank(e.sanitizer_name)
        if name and _norm_name(name) not in rows:
            rows[_norm_name(name)] = MaterialRow(name=name, kind="sanitizer", event=e)

    if osp is None:
        osp = _current_osp(establishment)
    if osp is not None:
        from certifications.services.plan_materials import plan_materials

        try:
            declared = plan_materials(osp)
        except Exception:  # noqa: BLE001 — an attachment must never fail over the plan's list
            logger.exception("Materials List: the plan's materials could not be read")
            declared = []
        for material in declared:
            name = _blank(material.name)
            if not name:
                continue
            key = _norm_name(name)
            existing = rows.get(key)
            if existing is None:
                # Declared but never applied — "intended for use", which is half of what this
                # form asks for and was missing from it entirely.
                rows[key] = MaterialRow(name=name, kind="plan", plan=material)
            else:
                rows[key] = MaterialRow(
                    name=existing.name,
                    kind=existing.kind,
                    event=existing.event,
                    plan=_richer_plan(existing.plan, material),
                )
    return list(rows.values())


