"""
Common OSP required attachments — the four workbooks, generated from Trazo records.

The Common OSP (USDA AMS, template files dated 2026-05-26) lists four forms that must accompany
the crop OSP when applicable:

    Field and Crop Information Form  — required for all fields requested for certification
    Crop/Livestock Product List     — required for all crop, wild crop, livestock operations
    Materials List                  — required when any nonorganic input is used
    Supplier List                   — required for suppliers of products used in production

Column headers below are VERBATIM from the USDA .xlsx files. Do not reword them. The whole point
is that a certifier receives something identical in shape to the form they already read; a
"clearer" header is how a generated attachment stops matching the official one.

## What this does and does not do

It fills the columns Trazo can answer from real records, and **leaves a cell blank rather than
guessing**. A blank cell is a prompt to the operator; an invented one is a false statement on a
regulatory attachment. That is the same rule the § 11 evidence derivation follows, and it matters
most on the Field and Crop Information form: USDA requires "Name and Application Date of Last
Prohibited Input" for EVERY field, *including fields already certified organic*. Trazo stores the
name (`ParcelCropHistory.last_prohibited_substance`) and the date
(`ParcelCropHistory.date_last_prohibited`) as separate fields precisely so this cell is either
answered from a record or left for the operator — it is never inferred from the free-text
`substances_applied` summary, which lists everything applied that year and cannot tell you which
one was the last prohibited one.

The generated workbooks are a **starting point the operator reviews and completes**, not a filed
form. Nothing here is submitted anywhere.
"""

from __future__ import annotations

import io
import logging
from dataclasses import dataclass, field
from typing import Callable, Optional

logger = logging.getLogger(__name__)

# Shown in the instruction row of every generated sheet, so a certifier opening the file knows
# where it came from and that a human still has to check it.
PROVENANCE = (
    "Generated by Trazo from the operation's own records on {date}. "
    "Blank cells are questions Trazo could not answer from your records — complete them before "
    "submitting. Review every row: you are the author of your Organic System Plan (7 CFR 205.201(a))."
)


@dataclass(frozen=True)
class Column:
    """One column of a USDA attachment form.

    `header` is verbatim from the USDA workbook. `value` receives the row's source object and
    returns a cell value, or None to leave the cell blank for the operator.
    """

    header: str
    value: Callable
    width: int = 22


@dataclass(frozen=True)
class Workbook:
    key: str
    # File name stem; the USDA form name, slugged.
    filename: str
    # Sheet title as it appears in the USDA file.
    title: str
    instructions: str
    columns: list
    # (establishment) -> iterable of row source objects
    rows: Callable
    # Opt-out declarations printed above the table on the USDA form, when applicable.
    declarations: list = field(default_factory=list)


#: Characters Excel refuses in a worksheet tab name. openpyxl raises ValueError on any of them.
_INVALID_SHEET_CHARS = set(r"\/?*[]:")


def _sheet_tab_name(title: str) -> str:
    """Excel-safe worksheet tab name (≤31 chars, no reserved punctuation)."""
    cleaned = "".join(" " if ch in _INVALID_SHEET_CHARS else ch for ch in title)
    return " ".join(cleaned.split())[:31]


def _blank(value) -> Optional[str]:
    """Empty string and whitespace become a blank cell, not the text 'None'."""
    if value is None:
        return None
    text = str(value).strip()
    return text or None


#: Excel treats a cell whose text starts with any of these as a FORMULA, not data.
_FORMULA_LEADERS = ("=", "+", "-", "@", "\t", "\r")


def _defuse_formula(value):
    """Stop farmer-entered text from executing as a formula in the certifier's spreadsheet.

    Every string in these workbooks originates as free text a farmer typed — product names,
    supplier names, crop names. Excel evaluates any cell beginning with = + - @ as a formula, so
    a value like `=HYPERLINK(...)` becomes live content in a file we hand to a third party. This
    is the classic CSV/formula-injection vector, and it matters more here than usual because the
    recipient is a certifier opening an attachment they were told came from a compliance tool.

    Prefixing with an apostrophe is Excel's own "treat as text" marker: it is not shown in the
    cell, and the value reads normally. Numbers and dates pass through untouched so the Acreage
    column stays numeric and sortable.
    """
    if not isinstance(value, str) or not value:
        return value
    return f"'{value}" if value.startswith(_FORMULA_LEADERS) else value


