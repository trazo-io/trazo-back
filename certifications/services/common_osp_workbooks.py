def _supplier_rows(establishment, osp=None):
    """Distinct suppliers of purchased products — inputs, amendments and seed.

    Keyed on (product, supplier) because the USDA form wants one row per product per supplier,
    not one row per supplier.

    🔴 2026-08-16: soil amendments were absent entirely, because `SoilManagementEvent` had no
    supplier column. On an organic orchard the compost supplier is usually the largest single
    line on this form, and the generated workbook simply did not have it.

    🔴 2026-08-17, the SECOND instance of that same defect: beneficial-organism suppliers were
    absent. The workbook's own USDA instruction line opens with "live animals", and a
    Trichogramma or lacewing release is bought from a named supplier exactly like a fertiliser
    is — `PestManagementEvent.beneficial_supplier` has held it since the BR subtype shipped and
    no row was ever emitted. Every event model that carries a supplier string belongs here; the
    lesson from two rounds is to enumerate the MODELS, not to remember the ones that came up.
    """
    from history.models import ChemicalEvent, PestManagementEvent, ProductionEvent, SoilManagementEvent

    seen = {}
    for e in ChemicalEvent.objects.filter(history__parcel__establishment=establishment):
        product, supplier = _blank(e.commercial_name), _blank(e.supplier_name)
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    for e in SoilManagementEvent.objects.filter(history__parcel__establishment=establishment):
        # Off-farm MANURE puts its supplier in `amendment_manufacturer`, by the convention
        # stated in SoilManagementEvent.manure_origin's own help_text ("a second supplier
        # field would be a second writer of one fact"). Reading only amendment_supplier_name
        # emitted zero Supplier List rows for exactly the operators who followed the model —
        # the third instance of this omission, after soil amendments (08-16) and beneficial
        # organisms (08-17). Those two enumerated the MODELS; this one is the FIELDS on a
        # model that can hold a supplier.
        supplier = _blank(e.amendment_supplier_name) or (
            _blank(e.amendment_manufacturer) if e.manure_origin == "off_farm" else None
        )
        # The product name, falling back to the generic category — a Supplier List row reading
        # "— / Bu's Compost Co." tells a certifier nothing about what was bought.
        product = _blank(e.amendment_product_name) or _blank(e.amendment_type)
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    seed_events = ProductionEvent.objects.filter(
        history__parcel__establishment=establishment, type__in=("PL", "TR")
    ).select_related("history__product", "history__crop_type")
    for e in seed_events:
        supplier = _blank(e.seed_supplier_name)
        # The CROP, not the production. `history.name` is a season label like
        # "Hass Avocado Hillside Grove A 2026"; writing that into the USDA "Product Name" column
        # describes a season to a certifier who expects the product the supplier provided.
        product = _blank(getattr(e.history.product, "name", None) or getattr(e.history.crop_type, "name", None))
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("seed", product, supplier)
    for e in PestManagementEvent.objects.filter(history__parcel__establishment=establishment):
        supplier = _blank(e.beneficial_supplier)
        # The organism, falling back to the generic category. A row reading "— / Rincon-Vitova"
        # tells a certifier nothing about what was released.
        product = _blank(e.beneficial_species) or "Beneficial organisms"
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    return list(seen.values())


