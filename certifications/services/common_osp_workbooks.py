def _field_rows(establishment):
    """One row per parcel per certification year, newest crop-history entry first.

    A parcel with no crop history still gets a row — the field exists and must appear on the
    form; its crop and prohibited-input cells are simply blank for the operator to fill.
    """
    from product.models import Parcel

    parcels = Parcel.objects.filter(establishment=establishment).prefetch_related("crop_history").order_by("name")
    rows = []
    for parcel in parcels:
        history = sorted(parcel.crop_history.all(), key=lambda h: h.year, reverse=True)
        if history:
            rows.append((parcel, history[0]))
        else:
            rows.append((parcel, None))
    return rows


def _product_rows(establishment):
    from history.models import History

    seen = {}
    for h in (
        History.objects.filter(parcel__establishment=establishment)
        .select_related("product", "crop_type")
        .order_by("product__name")
    ):
        name = getattr(h.product, "name", None) or getattr(h.crop_type, "name", None)
        if name and name not in seen:
            seen[name] = h
    return list(seen.values())


def _material_rows(establishment):
    """Distinct inputs applied on this operation — chemical products and soil amendments.

    Deduplicated by product name because the Materials List is a list of PRODUCTS, not of
    applications: an input sprayed twelve times is one row.
    """
    from history.models import ChemicalEvent, SoilManagementEvent

    seen = {}
    for e in ChemicalEvent.objects.filter(history__parcel__establishment=establishment):
        name = _blank(e.commercial_name)
        if name and name.lower() not in seen:
            seen[name.lower()] = ("chemical", e)
    for e in SoilManagementEvent.objects.filter(history__parcel__establishment=establishment):
        name = _blank(e.amendment_product_name)
        if name and name.lower() not in seen:
            seen[name.lower()] = ("amendment", e)
    return list(seen.values())


def _supplier_rows(establishment):
    """Distinct suppliers of purchased products — inputs and seed.

    Keyed on (product, supplier) because the USDA form wants one row per product per supplier,
    not one row per supplier.
    """
    from history.models import ChemicalEvent, ProductionEvent

    seen = {}
    for e in ChemicalEvent.objects.filter(history__parcel__establishment=establishment):
        product, supplier = _blank(e.commercial_name), _blank(e.supplier_name)
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("input", product, supplier)
    seed_events = ProductionEvent.objects.filter(
        history__parcel__establishment=establishment, type__in=("PL", "TR")
    ).select_related("history__product", "history__crop_type")
    for e in seed_events:
        supplier = _blank(e.seed_supplier_name)
        # The CROP, not the production. `history.name` is a season label like
        # "Hass Avocado Hillside Grove A 2026"; writing that into the USDA "Product Name" column
        # describes a season to a certifier who expects the product the supplier provided.
        product = _blank(getattr(e.history.product, "name", None) or getattr(e.history.crop_type, "name", None))
        if supplier and (product, supplier) not in seen:
            seen[(product, supplier)] = ("seed", product, supplier)
    return list(seen.values())


