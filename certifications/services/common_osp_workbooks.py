WORKBOOKS_BY_KEY = {w.key: w for w in WORKBOOKS}


def _material_reason(row):
    kind, event = row
    if kind == "amendment":
        return _blank(getattr(event, "amendment_type", None)) or "Soil amendment"
    subtype = getattr(event, "type", None)
    return {
        "FE": "Fertilizer",
        "PE": "Pest control",
        "FU": "Disease control",
        "HE": "Weed control",
    }.get(subtype)


