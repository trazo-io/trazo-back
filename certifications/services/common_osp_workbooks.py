# Shown in the instruction row of every generated sheet, so a certifier opening the file knows
# where it came from and that a human still has to check it.
PROVENANCE = (
    "Generated by Trazo from the operation's own records on {date}. "
    "Blank cells are questions Trazo could not answer from your records — complete them before "
    "submitting. Review every row: you are the author of your Organic System Plan (7 CFR 205.201(a))."
)


#: See `Column.blank_kind`. "record" is the default because it is the only one that says
#: Trazo could have answered and did not.
BLANK_KINDS = frozenset({"record", "operator", "optional"})

#: See `Column.fix_hint`. ⚠️ ADDING ONE IS A TWO-REPO CHANGE: the panel looks up
#: `osp.attachments.fix.<token>` for its wording, so a token with no message renders to the
#: farmer as that raw key. `ospAttachmentFixParity.test.ts` reads this set and fails without the
#: en-US and es-419 entries.
FIX_HINTS = frozenset(
    {
        "parcel",  # farm -> parcel -> edit: name, area
        "field_history",  # parcel -> field history: crop, status, last prohibited input
        "season",  # the production/season records: crop names, products sold
        "materials_list",  # OSP -> materials: manufacturer, reason for use, in use / intended
        "supplier_certificate",  # nowhere in Trazo -- it is on the supplier's own certificate
        "event_records",  # the activity records themselves: product name, supplier on an event
    }
)


@dataclass(frozen=True)
class Column:
    """One column of a USDA attachment form.

    `header` is verbatim from the USDA workbook. `value` receives the row's source object and
    returns a cell value, or None to leave the cell blank for the operator.
    """

    header: str
    value: Callable
    width: int = 22
    #: What a BLANK in this column means. The panel counts work from this, and counting it wrong
    #: is how a nearly-finished attachment reads as 48 cells of homework.
    #:
    #:   "record"   — Trazo fills it from a record. Blank = the record is missing, and the
    #:                operator can fix that IN Trazo, which is the only kind of blank the panel
    #:                should be nagging about.
    #:   "operator" — only the operator can answer it; no Trazo field could. Real work, but not
    #:                work Trazo can take off them (a supplier's own certifier, for instance).
    #:   "optional" — the USDA form permits a blank, or the sheet's own opt-out declaration
    #:                already covers it. NOT work, and counting it as work is a false statement
    #:                about how much is left.
    blank_kind: str = "record"
    #: WHERE in Trazo this column is answered. The panel turns it into a link.
    #:
    #: A count with no destination is the defect this closes: the attachments panel said "47
    #: cells to fill in Trazo" while offering nowhere to fill them, which is a promise the
    #: product did not keep and reads to a farmer as a fault in their data. Empty string means
    #: no Trazo screen answers it — legitimate for an `operator` blank (a supplier's own
    #: certificate) and a bug for a `record` one.
    fix_hint: str = ""

    def __post_init__(self):
        # A typo here would not raise and would not show: the count would silently land in a
        # bucket nothing reads, so a column of real work would report as zero work. Frozen
        # dataclass, so this is the only place to catch it.
        if self.blank_kind not in BLANK_KINDS:
            raise ValueError(
                f"{self.header!r}: blank_kind must be one of {sorted(BLANK_KINDS)}, got {self.blank_kind!r}"
            )
        if self.fix_hint and self.fix_hint not in FIX_HINTS:
            raise ValueError(
                f"{self.header!r}: unknown fix_hint {self.fix_hint!r}; expected one of {sorted(FIX_HINTS)}"
            )
        # A "record" blank is by definition one Trazo could have filled, so it has a screen the
        # operator fills it on. Without this, adding a column and forgetting the hint produces
        # the exact silent regression the hint exists to remove: a number with no destination.
        if self.blank_kind == "record" and not self.fix_hint:
            raise ValueError(f"{self.header!r}: a record-backed column must name where in Trazo it is answered")


@dataclass(frozen=True)
class Workbook:
    key: str
    # File name stem; the USDA form name, slugged.
    filename: str
    # Sheet title as it appears in the USDA file.
    title: str
    instructions: str
    columns: list
    # (establishment, osp) -> iterable of row source objects. EVERY row source takes both, even
    # the three that ignore the plan: a uniform signature is what lets `build_workbook` hand the
    # plan down without knowing which sheet cares, and the one that does care used to read
    # whichever plan happened to be active instead.
    rows: Callable
    # Opt-out declarations printed above the table on the USDA form, when applicable.
    declarations: list = field(default_factory=list)
    # Which certifying agents' packets carry this sheet. Empty = every packet (the four USDA Common
    # OSP attachments). A certifier's OWN form — OTCO's FACT-04 — ships only when the operation's
    # packet is numbered to that agent; a CCOF reviewer handed an Oregon Tilth table would read it
    # as a misfiled document. Register folder slugs ("otco"), matched against `packet_certifier`.
    agents: tuple = ()
    # (establishment, osp, rows) -> iterable of (label, value) pairs appended under the table. The
    # USDA attachments have no footer; OTCO's FACT-04 closes with two acreage totals the reviewer
    # reconciles against the certificate, and a total is a claim only the sheet's own rows can back.
    footer: Optional[Callable] = None


#: Characters Excel refuses in a worksheet tab name. openpyxl raises ValueError on any of them.
_INVALID_SHEET_CHARS = set(r"\/?*[]:")


def _sheet_tab_name(title: str) -> str:
    """Excel-safe worksheet tab name (≤31 chars, no reserved punctuation)."""
    cleaned = "".join(" " if ch in _INVALID_SHEET_CHARS else ch for ch in title)
    return " ".join(cleaned.split())[:31]


#: `Parcel.area` is stored in HECTARES. Every certifier-facing surface reports acres, so the
#: conversion belongs at the boundary — printing the stored number is how a 28.4-acre block
#: becomes "11.4931" on a form a certifier reconciles against the farm's stated total.
HECTARES_TO_ACRES = 2.47105


def _acres(area_hectares):
    """Parcel area in ACRES, rounded the way a grower states it, or None."""
    if area_hectares in (None, ""):
        return None
    try:
        return round(float(area_hectares) * HECTARES_TO_ACRES, 2)
    except (TypeError, ValueError):
        return None


def _blank(value) -> Optional[str]:
    """Empty string and whitespace become a blank cell, not the text 'None'."""
    if value is None:
        return None
    text = str(value).strip()
    return text or None


#: Excel treats a cell whose text starts with any of these as a FORMULA, not data.
_FORMULA_LEADERS = ("=", "+", "-", "@", "\t", "\r")


def _defuse_formula(value):
    """Stop farmer-entered text from executing as a formula in the certifier's spreadsheet.

    Every string in these workbooks originates as free text a farmer typed — product names,
    supplier names, crop names. Excel evaluates any cell beginning with = + - @ as a formula, so
    a value like `=HYPERLINK(...)` becomes live content in a file we hand to a third party. This
    is the classic CSV/formula-injection vector, and it matters more here than usual because the
    recipient is a certifier opening an attachment they were told came from a compliance tool.

    Prefixing with an apostrophe is Excel's own "treat as text" marker: it is not shown in the
    cell, and the value reads normally. Numbers and dates pass through untouched so the Acreage
    column stays numeric and sortable.
    """
    if not isinstance(value, str) or not value:
        return value
    return f"'{value}" if value.startswith(_FORMULA_LEADERS) else value


